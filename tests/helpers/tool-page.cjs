// A tool page as a reader gets it, for the tests that follow data from one tool into another: the built page from _site
// (its markup, its data file and, in German and Albanian, its texts), with the tool's own scripts run from src/js, so a
// change in a script is tested without building again. The tests that use it say what one tool writes and what the
// next one reads, through both tools' real code, instead of a fixture written in the shape the reader expects.
//
//   const w = openTool('waste-log', { lang: 'de', storage, now });
//   ... use the page ...
//   const storage = keep(w);      // everything the page left in localStorage, to open the next tool with
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');

const ROOT = path.join(__dirname, '..', '..');
const SITE = path.join(ROOT, '_site');

// The scripts the page runs for the tool itself: the texts of its language (ui-de.js, ui-sq.js) and everything from its
// data block on, up to the site-wide scripts that follow the tool (feedback, backup, sync, the header).
const SITE_WIDE = /^(feedback|storage-guard|work-backup|reminders|team-sync|tool-fold|offline|floor-mode|share-orbit|shelf|family-sky|work-lock|coaching-[a-z-]+|annotations|newsletter)$/;
const scriptsOf = (html) => [...html.matchAll(/<script src="\/(js\/)?([a-z0-9-]+)\.js(?:\?[^"]*)?"[^>]*><\/script>/g)]
  .map((match) => ({ dir: match[1] ? 'js' : '', name: match[2] }))
  .filter(({ dir, name }) => dir === 'js' && !SITE_WIDE.test(name));

const builtPage = (slug, lang) => {
  const file = path.join(SITE, lang === 'en' ? '' : lang, 'tools', slug, 'index.html');
  if (!fs.existsSync(file)) throw new Error(`${file} is missing: run npm run build first`);
  return fs.readFileSync(file, 'utf8');
};

// Date and Date.now fixed at `now`, as the other tool tests do, so "today" and "the last 30 days" are known.
const fixClock = (w, now) => w.eval(`(() => { const Real = Date; const fixed = new Real(${JSON.stringify(now)}); Date = class extends Real { constructor(...args) { super(...(args.length ? args : [fixed])); } static now() { return fixed.getTime(); } }; })();`);

// `code` replaces a script's source, e.g. an older version from git to produce data in an older format:
//   openTool('action-tracker', { code: { 'action-tracker': oldSource } }).
const openTool = (slug, { lang = 'en', storage = {}, now = '2026-10-25T11:00:00Z', search = '', scripts = null, code = {}, before = null } = {}) => {
  const html = builtPage(slug, lang);
  const list = scripts || scriptsOf(html);
  const body = html.replace(/<script src=[^>]*><\/script>/g, '');
  const url = `https://example.test${lang === 'en' ? '' : `/${lang}`}/tools/${slug}/${search}`;
  const dom = new JSDOM(body, { url, runScripts: 'outside-only', pretendToBeVisual: true });
  const w = dom.window;
  fixClock(w, now);
  w.confirm = () => true;
  w.alert = () => {};
  w.print = () => {};
  w.HTMLElement.prototype.scrollIntoView = () => {};
  w.URL.createObjectURL = () => 'blob:test';
  w.URL.revokeObjectURL = () => {};
  // jsdom has no TextEncoder/TextDecoder; the files the tools write (Excel, Word, PDF) need them.
  if (!w.TextEncoder) { w.TextEncoder = TextEncoder; w.TextDecoder = TextDecoder; }
  Object.entries(storage).forEach(([key, value]) => w.localStorage.setItem(key, typeof value === 'string' ? value : JSON.stringify(value)));
  // A last word before the scripts run, e.g. a full storage: before(w).
  if (before) before(w);
  for (const { name } of list) {
    if (code[name]) { w.eval(code[name]); continue; }
    // The texts of a language are generated by the build; the scripts are read from the source.
    const file = /^ui-(de|sq)$/.test(name) ? path.join(SITE, 'js', `${name}.js`) : path.join(ROOT, 'src', 'js', `${name}.js`);
    w.eval(fs.readFileSync(file, 'utf8'));
  }
  w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
  return w;
};

// What the page wrote: every localStorage key, as parsed JSON where it is JSON.
const keep = (w) => {
  w.dispatchEvent(new w.Event('pagehide'));
  const out = {};
  for (let i = 0; i < w.localStorage.length; i++) {
    const key = w.localStorage.key(i);
    const raw = w.localStorage.getItem(key);
    try { out[key] = JSON.parse(raw); } catch { out[key] = raw; }
  }
  return out;
};

const click = (w, node) => node.dispatchEvent(new w.MouseEvent('click', { bubbles: true, cancelable: true }));
const type = (w, input, value) => {
  input.value = value;
  input.dispatchEvent(new w.Event('input', { bubbles: true }));
  input.dispatchEvent(new w.Event('change', { bubbles: true }));
};
const submit = (w, form) => form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
// Waits for the timers and frames a page uses to save after drawing (ToolKit saves right after the next frame).
const settle = (w, ms = 30) => new Promise((resolve) => w.setTimeout(resolve, ms));

module.exports = { openTool, keep, click, type, submit, settle, scriptsOf, builtPage };
